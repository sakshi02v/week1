public class KilometersToMiles{
    public static void main(String [] args){
		
        //creating variable km of type double for storing value in kilometers
        double km=10.8;

        //using the formula -> 1km = 1.6 miles    
        double miles=km*1.6;
		
        //displaying result
        System.out.println(" The distance" + km + "km in miles is " + miles + "miles");
    }
} 

